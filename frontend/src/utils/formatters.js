export function formatNumber(val, decimals = 1) {
  if (val === null || val === undefined) return "0";
  return Number(val).toLocaleString(undefined, {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  });
}

export function formatPercent(val) {
  if (val === null || val === undefined) return "0%";
  return `${Number(val).toFixed(1)}%`;
}

export function downloadJsonFile(data, filename = "writing-fingerprint-profile.json") {
  const jsonStr = JSON.stringify(data, null, 2);
  const blob = new Blob([jsonStr], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function downloadMarkdownReport(analysis) {
  if (!analysis) return;
  const ov = analysis.overview;
  const md = `# AI Writing Fingerprint Analysis Report
**Document Name:** ${analysis.document_name}
**Generated Date:** ${new Date().toLocaleDateString()}

---

## 1. Executive Summary
${analysis.summary}

${analysis.reliability_warning ? `> **Notice:** ${analysis.reliability_warning}\n` : ''}

## 2. Quantitative Overview
- **Total Words:** ${ov.total_words}
- **Total Sentences:** ${ov.total_sentences}
- **Unique Words:** ${ov.unique_words}
- **Average Sentence Length:** ${ov.avg_sentence_length} words
- **Average Word Length:** ${ov.avg_word_length} characters
- **Lexical Diversity (Type-Token Ratio):** ${ov.lexical_diversity}
- **Hapax Legomena (Single-occurrence words):** ${ov.hapax_legomena_count} (${(ov.hapax_legomena_ratio * 100).toFixed(1)}% of vocabulary)

## 3. Grammatical / POS Distribution
- **Nouns:** ${analysis.linguistic.noun_pct}% (${analysis.linguistic.noun_count} tokens)
- **Verbs:** ${analysis.linguistic.verb_pct}% (${analysis.linguistic.verb_count} tokens)
- **Adjectives:** ${analysis.linguistic.adjective_pct}% (${analysis.linguistic.adjective_count} tokens)
- **Adverbs:** ${analysis.linguistic.adverb_pct}% (${analysis.linguistic.adverb_count} tokens)
- **Pronouns:** ${analysis.linguistic.pronoun_pct}% (${analysis.linguistic.pronoun_count} tokens)
- **Prepositions:** ${analysis.linguistic.preposition_pct}% (${analysis.linguistic.preposition_count} tokens)
- **Conjunctions:** ${analysis.linguistic.conjunction_pct}% (${analysis.linguistic.conjunction_count} tokens)

## 4. Sentence Extremes
- **Shortest Sentence (${analysis.sentence.shortest_sentence.length} words):**
  "${analysis.sentence.shortest_sentence.text}"
- **Longest Sentence (${analysis.sentence.longest_sentence.length} words):**
  "${analysis.sentence.longest_sentence.text}"

---
*Report generated by AI Writing Fingerprint — Stylometric Research Platform*
`;

  const blob = new Blob([md], { type: "text/markdown" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `${analysis.document_name.toLowerCase().replace(/[^a-z0-9]/g, "_")}_fingerprint_report.md`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

